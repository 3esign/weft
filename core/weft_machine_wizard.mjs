const LAYER_MARKER = /^;\s*(CHANGE_LAYER\b|LAYER_CHANGE\b|LAYER_COUNT:|LAYER:|layer\s+-?\d+\b)/;
const PER_LAYER_COMMENT = /^;\s*(CHANGE_LAYER\b|Z_HEIGHT:|LAYER_HEIGHT:|LAYER_CHANGE\b|Z:|HEIGHT:|LAYER:|LAYER_COUNT:|TIME_ELAPSED:|FEATURE:|TYPE:|LINE_WIDTH:|WIDTH:|MESH:|BEFORE_LAYER_CHANGE|AFTER_LAYER_CHANGE|layer num\/total_layer_count:|layer\s+-?\d+\b|\d*\.?\d+\s*$)/;
const TRAILING_META = /^;\s*(EXECUTABLE_BLOCK_END|SETTING_3\b|objects_info\b|prusaslicer_config\b|filament used\b|filament cost\b|total filament\b|estimated (first layer )?printing time\b|End of Gcode\b)/;

function findBlocks(lines){
  const moves = lines.map(parseMove);
  const ext = []; for(let i = 0; i < lines.length; i++) if(isExtrudingXY(moves[i])) ext.push(i);
  const marker = lines.findIndex(l => LAYER_MARKER.test(l));
  let cut, reason, purgeLines = 0;
  if(marker >= 0){
    cut = marker; reason = `first per-layer marker at line ${marker + 1}: ${lines[marker].trim()}`;
    purgeLines = ext.filter(i => i < marker).length;
  }else if(ext.length){
    /* rule 2: runs of extruding moves separated only by G0/G1 lines; a run closed by G92 E… is a purge */
    const runs = []; let run = null, lastIdx = -1;
    for(const i of ext){
      let onlyMoves = run !== null;
      if(run !== null) for(let k = lastIdx + 1; k < i; k++) if(lines[k].trim() && !moves[k]){ onlyMoves = false; break; }
      if(run !== null && onlyMoves) run.end = i; else { run = { start:i, end:i }; runs.push(run); }
      lastIdx = i;
    }
    cut = lines.length; reason = 'no per-layer marker and every extruding run is a purge (closed by G92 E): the file is a start block only';
    for(let r = 0; r < runs.length; r++){
      const next = r + 1 < runs.length ? runs[r + 1].start : lines.length;
      let closed = false; for(let k = runs[r].end + 1; k < next; k++) if(isExtruderReset(lines[k])){ closed = true; break; }
      if(closed){ purgeLines += ext.filter(i => i >= runs[r].start && i <= runs[r].end).length; continue; }
      cut = runs[r].start; reason = `no per-layer marker; first extruding XY move not closed by a G92 E reset, line ${cut + 1}`; break;
    }
  }else{ cut = lines.length; reason = 'no per-layer marker and no extruding move: the file is a start block only'; }
  let s = cut; while(s > 0 && !lines[s - 1].trim()) s--;
  const start = lines.slice(0, s).join('\n');
  const objExt = ext.filter(i => i >= cut);
  const firstExtrude = objExt.length ? objExt[0] : -1, lastExtrude = objExt.length ? objExt[objExt.length - 1] : -1;
  let end = '', endDropped = 0;
  if(lastExtrude >= 0){
    const kept = []; let inWipe = false, inCfg = false;
    for(let i = lastExtrude + 1; i < lines.length; i++){
      const l = lines[i], t = l.trim();
      if(/^;\s*WIPE_START/.test(t)){ inWipe = true; endDropped++; continue; }
      if(/^;\s*WIPE_END/.test(t)){ inWipe = false; endDropped++; continue; }
      if(/^; prusaslicer_config = begin/.test(t)){ inCfg = true; endDropped++; continue; }
      if(/^; prusaslicer_config = end/.test(t)){ inCfg = false; endDropped++; continue; }
      if(inWipe || inCfg || PER_LAYER_COMMENT.test(t) || TRAILING_META.test(t)){ endDropped++; continue; }
      kept.push(l);
    }
    while(kept.length && !kept[0].trim()) kept.shift();
    while(kept.length && !kept[kept.length - 1].trim()) kept.pop();
    end = kept.join('\n');
  }
  return {
    start, end,
    firstExtrudeLine: firstExtrude >= 0 ? firstExtrude + 1 : null,     // 1-based, first extruding XY move of the OBJECT
    lastExtrudeLine: lastExtrude >= 0 ? lastExtrude + 1 : null,
    startCut:{ line:cut + 1, reason, purgeExtrusionsKept:purgeLines },
    layerMarker: marker >= 0 ? lines[marker].trim() : null,
    endDroppedLines:endDropped,
    extrudingMoves:ext.length
  };
}

/* ---------------------------------------------------------------------------------------------------
   parseSlicerExport */
export function parseSlicerExport(input, opts = {}){
  const filename = opts.filename || (typeof input === 'string' ? 'input.gcode' : 'input.bin');
  const buf = Buffer.isBuffer(input) ? input : Buffer.from(String(input), 'utf8');
  if(!buf.length) throw new WizardRefusal(`${filename}: empty file`, 'empty');
  const stl = looksLikeStl(buf, filename);
  if(stl) throw new WizardRefusal(`${filename}: this is an STL (${stl}) — a model, not a sliced file. Slice it in the machine's own slicer and export G-code (Bambu/Orca: "Export plate sliced file" -> .gcode.3mf).`, 'stl');
  const source = { file:filename, sha256:sha256(buf), bytes:buf.length };
  let text, container = null;
  if(buf.length >= 4 && buf[0] === 0x50 && buf[1] === 0x4b && buf[2] === 0x03 && buf[3] === 0x04){
    let entries;
    try{ entries = zipRead(buf); }catch(e){ throw new WizardRefusal(`${filename}: zip container could not be read (${e.message})`, 'zip'); }
    const g = entries.find(x => x.name === 'Metadata/plate_1.gcode') || entries.find(x => /\.gcode$/i.test(x.name));
    if(!g) throw new WizardRefusal(`${filename}: a 3MF container without a sliced G-code member (${entries.length} members: ${entries.map(e => e.name).slice(0, 6).join(', ')}…). A project .3mf is a model; export the SLICED plate (.gcode.3mf).`, 'no-gcode-member');
    text = g.data.toString('utf8');
    container = { members:entries.map(e => e.name), gcodeMember:g.name, gcodeSha256:sha256(g.data),
      hasPlateJson:entries.some(e => e.name === 'Metadata/plate_1.json'), hasSliceInfo:entries.some(e => e.name === 'Metadata/slice_info.config'),
      projectSettings:entries.some(e => e.name === 'Metadata/project_settings.config') };
  }else{
    if(looksBinary(buf)) throw new WizardRefusal(`${filename}: not a text G-code file (binary content${MODEL_EXT.test(filename) ? `, extension ${path.extname(filename)}` : ''})`, 'binary');
    text = buf.toString('utf8');
  }
  const lines = text.split(/\r?\n/);
  if(!lines.some(l => /^\s*(N\d+\s+)?[GM]\d/i.test(l.split(';')[0]) || /^\s*[A-Z_]{4,}(\s|$)/.test(l.split(';')[0])))
    throw new WizardRefusal(`${filename}: no G-code commands found (not a sliced file)`, 'no-gcode');

  const det = detectFlavor(text);
  const warnings = [];
  let values = {}, config = {}, header = {};
  if(det.flavor === 'bambu' || det.flavor === 'orca'){
    const b = bambuConfig(lines); config = b.cfg; header = b.header;
    if(!b.hasConfigBlock) warnings.push('no CONFIG_BLOCK: only the header and the moves could be read');
    values = valuesBambuOrca(config, header);
  }else if(det.flavor === 'prusa'){
    const p = prusaConfig(lines); config = p.cfg; header = p.header;
    if(!p.hasConfigBlock) warnings.push('no "; prusaslicer_config" block: only the header could be read');
    values = valuesPrusa(config, header);
  }else if(det.flavor === 'cura'){
    const c = curaConfig(lines); header = c.header; config = Object.assign({}, c.settings.global, ...c.settings.extruders.map((e, i) => Object.fromEntries(Object.entries(e).map(([k, v]) => [`extruder${i}.${k}`, v]))));
    if(c.settingsError) warnings.push(c.settingsError);
    if(!c.settings.extruders.length && !Object.keys(c.settings.global).length) warnings.push('no ;SETTING_3 profile: Cura only writes the settings the user changed, and here there are none');
    values = valuesCura(header, c.settings);
    warnings.push('Cura ;SETTING_3 carries only the settings changed from the printer definition; anything missing here is in the definition file, not in the export');
  }else{
    values = valuesUnknown(lines);
    warnings.push('no known slicer signature: values come from the moves and the temperature lines only');
  }
  for(const k of Object.keys(values)) if(values[k] == null) delete values[k];
  const blocks = findBlocks(lines);
  /* temperatures the config did not state (Cura writes only what the user changed) are still on the
     start block's own M104/M109/M140/M190 lines — keyed as such, so the reader knows where they came from */
  if(det.flavor !== 'unknown' && (!values.temp || !values.bed)){
    const fromStart = valuesUnknown(blocks.start.split('\n'));
    if(!values.temp && fromStart.temp) values.temp = fromStart.temp;
    if(!values.bed && fromStart.bed) values.bed = fromStart.bed;
  }
  if(blocks.firstExtrudeLine == null) warnings.push('no object in the file (start block only): no end block could be harvested');
  if(det.flavor === 'unknown' && blocks.layerMarker == null && blocks.firstExtrudeLine != null) warnings.push(`start block cut by heuristic (${blocks.startCut.reason}); read it before trusting it`);
  /* layer height from the moves, when the config did not say */
  if(!values.layerHeight && blocks.firstExtrudeLine != null){
    const zs = new Set(); let z = 0;
    for(let i = blocks.startCut.line - 1; i < lines.length; i++){ const d = parseMove(lines[i]); if(!d) continue; if('Z' in d) z = d.Z; if(isExtrudingXY(d)) zs.add(round(z, 3)); }
    const sorted = [...zs].sort((a, b) => a - b); let best = null;
    for(let i = 1; i < sorted.length; i++){ const dz = round(sorted[i] - sorted[i - 1], 3); if(dz > 0.02 && (best == null || dz < best)) best = dz; }
    if(best != null) values.layerHeight = { value:best, key:'derived: smallest Z step between extruding layers', raw:`${sorted.length} distinct Z` };
  }
  return { flavor:det.flavor, slicer:det.slicer, version:det.version, signature:det.signature, values, config, header, blocks, container, source, warnings };
}

/* ---------------------------------------------------------------------------------------------------
   templating: literal temperatures -> {TEMP} / {BED} (see the header comment) */
export function templateStartBlock(start, temps, beds){
  const T = new Set(temps.filter(v => v != null && v > 0)), B = new Set(beds.filter(v => v != null && v > 0));
  const sub = (line, cmdRe, set, tag) => line.replace(cmdRe, (m, pre, val) => set.has(+val) ? `${pre}{${tag}}` : m);
  const replaced = { TEMP:0, BED:0 };
  const out = start.split('\n').map(line => {
    let l = line;
    l = sub(l, /^(\s*M10[49]\b[^;]*?\bS)(\d+(?:\.\d+)?)/i, T, 'TEMP');
    l = sub(l, /^(\s*M1[49]0\b[^;]*?\bS)(\d+(?:\.\d+)?)/i, B, 'BED');
    l = sub(l, /^([A-Z_]+\b[^;]*?\b(?:EXTRUDER(?:_TEMP)?|HOTEND(?:_TEMP)?|NOZZLE_TEMP|TOOL_TEMP)=)(\d+(?:\.\d+)?)/i, T, 'TEMP');
    l = sub(l, /^([A-Z_]+\b[^;]*?\bBED(?:_TEMP)?=)(\d+(?:\.\d+)?)/i, B, 'BED');
    if(l !== line){ if(l.includes('{TEMP}') && !line.includes('{TEMP}')) replaced.TEMP++; if(l.includes('{BED}') && !line.includes('{BED}')) replaced.BED++; }
    return l;
  }).join('\n');
  return { text:out, replaced };
}

/* ---------------------------------------------------------------------------------------------------
   profileFromExport */
const ASSUMED = { plate:[220, 220], maxZ:250, nozzle:0.4, lh:0.2, temp:220, bed:60 };
export function profileFromExport(parsed, opts = {}){
  const id = String(opts.id || '').trim();
  if(!/^[a-z][a-z0-9_-]{0,63}$/i.test(id)) throw new WizardRefusal(`--id "${id}" must be a plain identifier (letters, digits, _ -), it becomes a file name`, 'bad-id');
  const label = opts.label || (parsed.values.printerModel ? parsed.values.printerModel.value : id);
  const outDir = opts.outDir != null ? String(opts.outDir) : '';
  const V = parsed.values, src = parsed.source;
  const prov = {}, needsReview = [];
  const from = (field, v, note) => { prov[field] = { value:v.value, source:'slicer-export', key:v.key, raw:v.raw, file:src.file, sha256:src.sha256 }; if(note) prov[field].note = note; return v.value; };
  const assume = (field, value, why) => { prov[field] = { value, source:'assumed', key:null, file:src.file, sha256:src.sha256, why }; needsReview.push(field); return value; };
  const take = (field, v, fallback, why) => v ? from(field, v) : assume(field, fallback, why);

  prov.label = { value:label, source:opts.label ? 'caller' : (V.printerModel ? 'slicer-export' : 'caller'), key:opts.label ? '--label' : (V.printerModel ? V.printerModel.key : '--id'), file:src.file, sha256:src.sha256 };
  const plate = take('plate', V.plate, ASSUMED.plate, 'the export does not state the bed shape');
  const maxZ = take('maxZ', V.maxZ, ASSUMED.maxZ, 'the export does not state the printable height');
  const nozzle = take('nozzle', V.nozzle, ASSUMED.nozzle, 'the export does not state the nozzle diameter');
  const lh = take('lh', V.layerHeight, ASSUMED.lh, 'the export does not state the layer height');
  const temp = take('temp', V.temp, V.firstLayerTemp ? V.firstLayerTemp.value : ASSUMED.temp, V.firstLayerTemp ? 'only the first-layer nozzle temperature was found; used for every layer' : 'the export does not state a nozzle temperature');
  const bed = take('bed', V.bed, V.firstLayerBed ? V.firstLayerBed.value : ASSUMED.bed, V.firstLayerBed ? 'only the first-layer bed temperature was found; used for every layer' : 'the export does not state a bed temperature');

  /* THE BEAD. Never from an export. A line width is what the slicer was told to aim for; a bead is what
     the machine laid down, measured with calipers on the C1 coupon. So bead is always `assumed`, and the
     evidence says why — even when the number itself came from the export's line width. */
  const beadFrom = V.lineWidth ? `slicer line width ${V.lineWidth.value} (${V.lineWidth.key})` : `nozzle × 1.125 (the A2L measured 0.45 on a 0.4 nozzle)`;
  const bead = V.lineWidth ? round(V.lineWidth.value, 3) : round(nozzle * 1.125, 2);
  const beadEvidence = `NEVER CALIBRATED on this machine; run the C1 coupon (core/weft_c1_calibration.mjs) and put the measured width here. Starting number is ${beadFrom}, which is a slicer setting, not a measured bead.`;
  prov.bead = { value:bead, source:'assumed', key:V.lineWidth ? V.lineWidth.key : null, raw:V.lineWidth ? V.lineWidth.raw : null, file:src.file, sha256:src.sha256, why:beadEvidence };
  needsReview.push('bead');
  const flbFrom = V.firstLayerLineWidth ? `slicer first-layer line width ${V.firstLayerLineWidth.value} (${V.firstLayerLineWidth.key})` : 'bead × 1.15 (the ratio machines.json uses: 0.52/0.45, 0.48/0.42)';
  const firstLayerBead = V.firstLayerLineWidth ? round(V.firstLayerLineWidth.value, 3) : round(bead * 1.15, 2);
  prov.firstLayerBead = { value:firstLayerBead, source:'assumed', key:V.firstLayerLineWidth ? V.firstLayerLineWidth.key : null, raw:V.firstLayerLineWidth ? V.firstLayerLineWidth.raw : null, file:src.file, sha256:src.sha256, why:`same status as bead; starting number is ${flbFrom}` };
  needsReview.push('firstLayerBead');

  /* the rest of what was read, kept beside the entry for the person reading it */
  const extra = ['firstLayerHeight', 'firstLayerTemp', 'firstLayerBed', 'bedType', 'bedOrigin', 'lineWidth', 'firstLayerLineWidth', 'filamentDiameter', 'retractLength', 'retractSpeed', 'zHop', 'firstLayerSpeed', 'fanMin', 'fanMax', 'fanFirstLayer', 'fanOffFirstLayers', 'gcodeFlavor', 'printerModel', 'printerSettingsId', 'filamentType'];
  for(const f of extra) if(V[f]) from(f, V[f]);

  /* blocks */
  const startRaw = parsed.blocks.start, endRaw = parsed.blocks.end;
  const tpl = templateStartBlock(startRaw, [V.temp && V.temp.value, V.firstLayerTemp && V.firstLayerTemp.value], [V.bed && V.bed.value, V.firstLayerBed && V.firstLayerBed.value]);
  const startFile = `${id}_start.gcode`, endFile = `${id}_end.gcode`;
  const join = f => outDir ? (outDir.replace(/[\\/]+$/, '') + '/' + f) : f;
  prov.start = { value:join(startFile), source:'slicer-export', key:`start block rule: ${parsed.blocks.startCut.reason}`, file:src.file, sha256:src.sha256, lines:startRaw ? startRaw.split('\n').length : 0, templated:tpl.replaced, purgeExtrusionsKept:parsed.blocks.startCut.purgeExtrusionsKept };
  if(!tpl.replaced.TEMP && !tpl.replaced.BED) needsReview.push('start (no temperature line could be templated to {TEMP}/{BED})');
  prov.end = { value:join(endFile), source:'slicer-export', key:parsed.blocks.lastExtrudeLine ? `end block rule: after the last extruding XY move (line ${parsed.blocks.lastExtrudeLine}), ${parsed.blocks.endDroppedLines} per-layer/config lines dropped` : 'no object in the export: end block empty', file:src.file, sha256:src.sha256, lines:endRaw ? endRaw.split('\n').length : 0 };
  if(!endRaw) needsReview.push('end (empty: the export had no object after its start block)');

  const route = parsed.container && (parsed.flavor === 'bambu' || parsed.flavor === 'orca') ? 'bambu3mf' : 'gcode';
  prov.route = { value:route, source:'slicer-export', key:parsed.container ? `input is a ${parsed.flavor} .gcode.3mf container` : `input is plain G-code (${parsed.flavor})`, file:src.file, sha256:src.sha256 };

  const entry = {
    label, plate, maxZ, nozzle, bead, beadSource:'ASSUMED', beadEvidence, lh, firstLayerBead, temp, bed,
    start:join(startFile), end:join(endFile), route
  };
  if(route === 'bambu3mf'){
    const rel = path.isAbsolute(src.file) && src.file.startsWith(WEFT_ROOT) ? path.relative(WEFT_ROOT, src.file).split(path.sep).join('/') : src.file;
    entry.containerTemplate = rel;
    const ok = parsed.container.hasPlateJson && parsed.container.hasSliceInfo;
    prov.containerTemplate = { value:rel, source:'slicer-export', key:ok ? 'the export itself: it carries Metadata/plate_1.gcode, plate_1.json and slice_info.config, which packBambu3mf rewrites' : 'the export itself, but plate_1.json / slice_info.config are missing — packBambu3mf needs them', file:src.file, sha256:src.sha256 };
    if(!ok) needsReview.push('containerTemplate');
  }
  entry.v2 = {
    schema:'weft.machine.v2', wizard:WIZARD_VERSION, id,
    source:{ file:src.file, sha256:src.sha256, bytes:src.bytes, flavor:parsed.flavor, slicer:parsed.slicer, version:parsed.version, signature:parsed.signature,
      gcodeMember:parsed.container ? parsed.container.gcodeMember : null, gcodeSha256:parsed.container ? parsed.container.gcodeSha256 : src.sha256 },
    provenance:prov,
    bead:{ w:bead, source:'assumed', evidence:'never calibrated on this machine; run the C1 coupon', startingNumber:beadFrom },
    route,
    start:{ file:startFile, contents:tpl.text, harvested:startRaw, cut:parsed.blocks.startCut, layerMarker:parsed.blocks.layerMarker },
    end:{ file:endFile, contents:endRaw, lastExtrudeLine:parsed.blocks.lastExtrudeLine },
    files:{ [startFile]:tpl.text, [endFile]:endRaw },
    needsReview, warnings:parsed.warnings,
    note:'CANDIDATE. Nothing here has been printed. bead and firstLayerBead are assumed until the C1 coupon is measured on this machine; machines.json paths are repo-relative, adjust start/end/containerTemplate when you copy the entry.'
  };
  return entry;
}

/* ---------------------------------------------------------------------------------------------------
   test helper: the HEADER_BLOCK statistics belong to the print the block came from ("1d 1h 26m 54s" vs
   "45m 36s", 583 vs 40 layers); blank their values so two harvests of the same machine compare equal.
   The slicer version line ("; BambuStudio 02.07.01.62") has no ':' and is kept as it is. */
export function stripHeaderStatistics(text){
  const L = text.split('\n'); let inHdr = false;
  return L.map(l => {
    if(l.startsWith('; HEADER_BLOCK_START')){ inHdr = true; return l; }
    if(l.startsWith('; HEADER_BLOCK_END')){ inHdr = false; return l; }
    return inHdr ? l.replace(/:.*$/, ': #') : l;
  }).join('\n');
}

/* ---------------------------------------------------------------------------------------------------
   CLI */
function summary(entry, parsed){
  const P = entry.v2.provenance, out = [];
  const fmt = v => Array.isArray(v) ? `[${v.join(', ')}]` : (typeof v === 'object' && v !== null ? JSON.stringify(v) : String(v));
  out.push(`WEFT slicer-export wizard ${WIZARD_VERSION}`);
  out.push(`  file     ${parsed.source.file} (${parsed.source.bytes} bytes, sha256 ${parsed.source.sha256.slice(0, 16)}…)`);
  out.push(`  slicer   ${parsed.slicer || '(none recognised)'} ${parsed.version || ''}  flavor=${parsed.flavor}${parsed.container ? `  container member ${parsed.container.gcodeMember}` : ''}`);
  out.push(`  route    ${entry.route}${entry.containerTemplate ? `  containerTemplate=${entry.containerTemplate}` : ''}`);
  out.push('');
  out.push('  field                value                    source          key');
  const order = ['label', 'plate', 'maxZ', 'nozzle', 'bead', 'firstLayerBead', 'lh', 'temp', 'bed', 'start', 'end', 'route', 'containerTemplate'];
  const rest = Object.keys(P).filter(k => !order.includes(k));
  for(const k of order.concat(rest)){
    if(!P[k]) continue; const p = P[k];
    out.push(`  ${k.padEnd(20)} ${fmt(p.value).padEnd(24)} ${p.source.padEnd(15)} ${p.key || '—'}${p.why ? `\n${''.padEnd(63)}why: ${p.why}` : ''}`);
  }
  out.push('');
  out.push(`  start block: ${P.start.lines} lines, ${P.start.purgeExtrusionsKept} purge extrusion(s) kept, templated {TEMP}×${P.start.templated.TEMP} {BED}×${P.start.templated.BED}`);
  out.push(`               cut: ${parsed.blocks.startCut.reason}`);
  out.push(`  end block:   ${P.end.lines} lines${parsed.blocks.lastExtrudeLine ? ` (after line ${parsed.blocks.lastExtrudeLine}, the last extruding move)` : ' (none)'}`);
  if(entry.v2.needsReview.length) out.push(`  NEEDS REVIEW: ${entry.v2.needsReview.join('; ')}`);
  for(const w of parsed.warnings) out.push(`  warning: ${w}`);
  out.push('');
  out.push('  The bead is ASSUMED. A slicer line width is a setting; a bead is measured in plastic. Run the C1 coupon before building for this machine.');
  return out.join('\n');
}

export function runCli(argv){
  const args = { _:[] };
  for(let i = 0; i < argv.length; i++){
    const a = argv[i];
    if(a.startsWith('--')){ const k = a.slice(2); if(i + 1 < argv.length && !argv[i + 1].startsWith('--')) args[k] = argv[++i]; else args[k] = true; }
    else args._.push(a);
  }
  const file = args._[0];
  if(!file || args.help || !args.id || !args.out){
    process.stderr.write('usage: node core/weft_machine_wizard.mjs FILE --id NAME --label "Printer label" --out DIR\n  FILE: a .gcode or .gcode.3mf exported by Bambu Studio, OrcaSlicer, PrusaSlicer or Cura (or any G-code file)\n  writes DIR/<id>_start.gcode, DIR/<id>_end.gcode, DIR/<id>.machine.json — never machines.json\n');
    return 2;
  }
  let parsed, entry;
  try{
    parsed = parseSlicerExport(fs.readFileSync(file), { filename:file });
    entry = profileFromExport(parsed, { id:args.id, label:args.label, outDir:args.out });
  }catch(e){
    if(e instanceof WizardRefusal){ process.stderr.write(`REFUSED (${e.code}): ${e.message}\n`); return 1; }
    throw e;
  }
  const outDir = path.resolve(args.out);
  fs.mkdirSync(outDir, { recursive:true });
  /* on disk the blocks live in their own files; the JSON keeps their names, sizes and hashes, not three copies */
  const onDisk = JSON.parse(JSON.stringify(entry));
  const blockRef = (b, text) => ({ file:b.file, lines:text ? text.split('\n').length : 0, sha256:sha256(Buffer.from(text, 'utf8')), cut:b.cut, layerMarker:b.layerMarker, lastExtrudeLine:b.lastExtrudeLine });
  onDisk.v2.start = blockRef(entry.v2.start, entry.v2.start.contents);
  onDisk.v2.end = blockRef(entry.v2.end, entry.v2.end.contents);
  delete onDisk.v2.files;
  const writes = [[entry.v2.start.file, entry.v2.start.contents], [entry.v2.end.file, entry.v2.end.contents], [`${args.id}.machine.json`, JSON.stringify({ [args.id]:onDisk }, null, 2) + '\n']];
  for(const [name, contents] of writes){
    const target = path.join(outDir, name);
    /* never outside the out dir, never machines.json */
    if(path.dirname(target) !== outDir || path.basename(target) === 'machines.json') throw new Error(`refusing to write ${target}`);
    fs.writeFileSync(target, contents);
  }
  process.stdout.write(summary(entry, parsed) + '\n\n  wrote ' + writes.map(w => path.join(args.out, w[0])).join(', ') + '\n');
  return 0;
}

