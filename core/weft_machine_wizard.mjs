function valuesCura(header, settings){
  const V = {};
  const ext = settings.extruders[0] || {}, glob = settings.global || {};
  const both = Object.assign({}, glob, ext);            // extruder [values] override global ones
  const S = 'SETTING_3:values';
  V.nozzle = pick(both, ['machine_nozzle_size'], S) || pick(header, ['Nozzle diameter'], 'header');
  V.layerHeight = pick(both, ['layer_height'], S) || pick(header, ['Layer height'], 'header');
  V.firstLayerHeight = pick(both, ['layer_height_0'], S);
  V.lineWidth = pick(both, ['wall_line_width_0', 'wall_line_width', 'line_width'], S);
  const ilf = pick(both, ['initial_layer_line_width_factor'], S);
  if(ilf && V.lineWidth) V.firstLayerLineWidth = { value:round(V.lineWidth.value * ilf.value / 100, 4), key:`${V.lineWidth.key} × ${ilf.key}`, raw:`${V.lineWidth.raw} × ${ilf.raw}%` };
  V.temp = pick(both, ['material_print_temperature'], S);
  V.firstLayerTemp = pick(both, ['material_print_temperature_layer_0'], S);
  V.bed = pick(both, ['material_bed_temperature'], S);
  V.firstLayerBed = pick(both, ['material_bed_temperature_layer_0'], S);
  const w = pick(both, ['machine_width'], S), d = pick(both, ['machine_depth'], S);
  if(w && d) V.plate = { value:[w.value, d.value], key:`${w.key} × ${d.key}`, raw:`${w.raw} × ${d.raw}` };
  V.maxZ = pick(both, ['machine_height'], S);
  V.filamentDiameter = pick(both, ['material_diameter'], S);
  V.retractLength = pick(both, ['retraction_amount'], S);
  V.retractSpeed = pick(both, ['retraction_retract_speed', 'retraction_speed'], S);
  const hopOn = pick(both, ['retraction_hop_enabled'], S, s => s);
  V.zHop = pick(both, ['retraction_hop'], S);
  if(V.zHop && hopOn && /false/i.test(hopOn.value)) V.zHop = { value:0, key:`${hopOn.key} = False (retraction_hop ignored)`, raw:hopOn.raw };
  V.firstLayerSpeed = pick(both, ['speed_layer_0', 'speed_print_layer_0'], S);
  V.fanMin = pick(both, ['cool_fan_speed_min', 'cool_fan_speed'], S);
  V.fanMax = pick(both, ['cool_fan_speed_max', 'cool_fan_speed'], S);
  V.fanFirstLayer = pick(both, ['cool_fan_speed_0'], S);
  V.gcodeFlavor = pick(both, ['machine_gcode_flavor'], S, s => s) || pick(header, ['FLAVOR'], 'header', s => s);
  V.printerModel = pick(header, ['TARGET_MACHINE.NAME'], 'header', s => s) || pick(both, ['machine_name'], S, s => s);
  return V;
}
/* unknown flavour: temperatures from the first M104/M109 and M140/M190 with a numeric S, and a layer
   height from the Z steps of the extruding moves (when the file has an object at all) */
function valuesUnknown(lines){
  const V = {};
  for(const l of lines){
    const b = l.split(';')[0];
    let m;
    if(!V.temp && (m = /^\s*M10[49]\s+.*?\bS(\d+(?:\.\d+)?)/i.exec(b)) && +m[1] > 0) V.temp = { value:+m[1], key:`${b.trim().split(/\s+/)[0]} S (start G-code line)`, raw:b.trim() };
    if(!V.bed && (m = /^\s*M1[49]0\s+.*?\bS(\d+(?:\.\d+)?)/i.exec(b)) && +m[1] > 0) V.bed = { value:+m[1], key:`${b.trim().split(/\s+/)[0]} S (start G-code line)`, raw:b.trim() };
    if(!V.temp && (m = /\b(?:EXTRUDER(?:_TEMP)?|HOTEND(?:_TEMP)?|NOZZLE_TEMP|TOOL_TEMP)=(\d+(?:\.\d+)?)/i.exec(b))) V.temp = { value:+m[1], key:'macro argument (start G-code line)', raw:b.trim() };
    if(!V.bed && (m = /\bBED(?:_TEMP)?=(\d+(?:\.\d+)?)/i.exec(b))) V.bed = { value:+m[1], key:'macro argument (start G-code line)', raw:b.trim() };
  }
  return V;
}

