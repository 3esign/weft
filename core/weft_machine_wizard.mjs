/* ---------------------------------------------------------------------------------------------------
   flavor detection: what each parser keys on */
function detectFlavor(text){
  const head = text.slice(0, 64 * 1024);
  let m;
  if((m = /^;\s*generated by OrcaSlicer\s+(\S+)/mi.exec(head)))
    return { flavor:'orca', slicer:'OrcaSlicer', version:m[1], signature:m[0].trim() };
  if((m = /^;\s*BambuStudio\s+(\S+)/mi.exec(head)) || (m = /^;\s*generated by BambuStudio\s+(\S+)/mi.exec(head)))
    return { flavor:'bambu', slicer:'BambuStudio', version:m[1], signature:m[0].trim() };
  if(/^; HEADER_BLOCK_START/m.test(head) && /^; CONFIG_BLOCK_START/m.test(text))
    return { flavor:'bambu', slicer:'BambuStudio', version:null, signature:'; HEADER_BLOCK_START + ; CONFIG_BLOCK_START (no version line)' };
  if((m = /^;\s*generated by (PrusaSlicer|SuperSlicer|Slic3r PE|Slic3r)\s+(\S+)/mi.exec(head)))
    return { flavor:'prusa', slicer:m[1], version:m[2], signature:m[0].trim() };
  if((m = /^;Generated with (\S+)\s*(\S*)/m.exec(head)) && /^;FLAVOR:/m.test(head)){
    const slicer = /Cura_SteamEngine/i.test(m[1]) ? 'Cura' : m[1];
    return { flavor:'cura', slicer, version:m[2] || null, signature:m[0].trim() };
  }
  return { flavor:'unknown', slicer:null, version:null, signature:null };
}

/* ---------------------------------------------------------------------------------------------------
   config readers — every one returns a flat { key: rawString } map (plus a `keyPrefix` for provenance) */
function readKeyEqValue(lines, from, to, map){
  for(let i = from; i < to; i++){
    const m = /^;\s*([^=\s][^=]*?)\s*=\s?(.*)$/.exec(lines[i]);
    if(m) map[m[1]] = m[2];
  }
}
function bambuConfig(lines){
  const cfg = {}, header = {};
  const cs = lines.findIndex(l => l.startsWith('; CONFIG_BLOCK_START')), ce = lines.findIndex(l => l.startsWith('; CONFIG_BLOCK_END'));
  if(cs >= 0 && ce > cs) readKeyEqValue(lines, cs + 1, ce, cfg);
  const hs = lines.findIndex(l => l.startsWith('; HEADER_BLOCK_START')), he = lines.findIndex(l => l.startsWith('; HEADER_BLOCK_END'));
  if(hs >= 0 && he > hs) for(let i = hs + 1; i < he; i++){ const m = /^;\s*([^:]+?)\s*:\s*(.*)$/.exec(lines[i]); if(m) header[m[1]] = m[2]; }
  return { cfg, header, hasConfigBlock:cs >= 0 && ce > cs };
}
function prusaConfig(lines){
  const cfg = {}, header = {};
  const cs = lines.findIndex(l => /^; prusaslicer_config = begin/.test(l)), ce = lines.findIndex(l => /^; prusaslicer_config = end/.test(l));
  if(cs >= 0 && ce > cs) readKeyEqValue(lines, cs + 1, ce, cfg);
  /* the header's derived extrusion widths: "; external perimeters extrusion width = 0.45mm" */
  for(let i = 0; i < Math.min(lines.length, 60); i++){ const m = /^;\s*(.+?extrusion width)\s*=\s*(.*)$/.exec(lines[i]); if(m) header[m[1]] = m[2]; }
  return { cfg, header, hasConfigBlock:cs >= 0 && ce > cs, configRange:[cs, ce] };
}
function curaConfig(lines){
  const header = {};
  for(let i = 0; i < Math.min(lines.length, 60); i++){
    const m = /^;([A-Za-z][A-Za-z0-9_. ]*?):(.*)$/.exec(lines[i]);
    if(m) header[m[1]] = m[2].trim();
  }
  /* ;SETTING_3 fragments: concatenate, JSON.parse, then read the INI-ish [values] sections */
  const frag = lines.filter(l => l.startsWith(';SETTING_3 ')).map(l => l.slice(';SETTING_3 '.length)).join('');
  const settings = { global:{}, extruders:[] }; let settingsError = null;
  if(frag){
    try{
      const j = JSON.parse(frag);
      const values = txt => { const out = {}; let inValues = false;
        for(const raw of String(txt).split('\n')){ const l = raw.trim();
          if(/^\[.*\]$/.test(l)){ inValues = l === '[values]'; continue; }
          if(!inValues || !l) continue; const eq = l.indexOf('='); if(eq > 0) out[l.slice(0, eq).trim()] = l.slice(eq + 1).trim(); }
        return out; };
      if(j.global_quality) settings.global = values(j.global_quality);
      for(const e of (j.extruder_quality || [])) settings.extruders.push(values(e));
    }catch(e){ settingsError = `;SETTING_3 fragments did not parse as JSON: ${e.message}`; }
  }
  return { header, settings, settingsError };
}

/* ---------------------------------------------------------------------------------------------------
   value extraction. Every extracted value is { value, key, raw } — `key` is the exact source key. */
function pick(map, keys, prefix, transform){
  for(const k of keys){
    if(map[k] == null) continue;
    const raw = String(map[k]).trim();
    if(raw === '' || raw === '""' || raw === 'nil') continue;
    const v = transform ? transform(raw) : num(firstOf(raw));
    if(v == null || (typeof v === 'number' && Number.isNaN(v))) continue;
    return { value:v, key:(prefix ? prefix + ':' : '') + k, raw };
  }
  return null;
}
/* "0x0,330x0,330x320,0x320" (Bambu printable_area, Prusa bed_shape) -> { plate:[w,h], origin:[x,y] } */
function bedShape(raw){
  const pts = String(raw).split(',').map(p => p.trim().split(/x/i).map(Number)).filter(p => p.length === 2 && p.every(Number.isFinite));
  if(pts.length < 3) return null;
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const minx = Math.min(...xs), miny = Math.min(...ys), maxx = Math.max(...xs), maxy = Math.max(...ys);
  return { plate:[round(maxx - minx), round(maxy - miny)], origin:[minx, miny], points:pts };
}
const BED_TYPE_KEY = {           // Bambu/Orca curr_bed_type -> the config key that holds its temperature
  'Cool Plate':'cool_plate_temp', 'Cool Plate (SuperTack)':'supertack_plate_temp', 'Supertack Plate':'supertack_plate_temp',
  'Engineering Plate':'eng_plate_temp', 'High Temp Plate':'hot_plate_temp', 'Textured PEI Plate':'textured_plate_temp',
  'Textured Cool Plate':'textured_cool_plate_temp', 'Smooth Cool Plate':'cool_plate_temp', 'Smooth High Temp Plate':'hot_plate_temp'
};

function valuesBambuOrca(cfg, header){
  const V = {}, P = 'config';
  V.nozzle = pick(cfg, ['nozzle_diameter'], P);
  V.layerHeight = pick(cfg, ['layer_height'], P);
  V.firstLayerHeight = pick(cfg, ['initial_layer_print_height'], P);
  V.lineWidth = pick(cfg, ['line_width', 'outer_wall_line_width', 'inner_wall_line_width'], P);
  V.firstLayerLineWidth = pick(cfg, ['initial_layer_line_width'], P);
  V.temp = pick(cfg, ['nozzle_temperature'], P);
  V.firstLayerTemp = pick(cfg, ['nozzle_temperature_initial_layer'], P);
  const bedType = firstOf(cfg.curr_bed_type || '') || null;
  const bk = bedType && BED_TYPE_KEY[bedType];
  const bedKeys = bk ? [bk] : Object.keys(cfg).filter(k => /_plate_temp$/.test(k)).sort();
  V.bed = pick(cfg, bedKeys.concat(['bed_temperature']), P);
  V.firstLayerBed = pick(cfg, bedKeys.map(k => k + '_initial_layer').concat(['bed_temperature_initial_layer']), P);
  if(bedType && (V.bed || V.firstLayerBed)) V.bedType = { value:bedType, key:'config:curr_bed_type', raw:cfg.curr_bed_type };
  const shape = pick(cfg, ['printable_area', 'bed_shape'], P, bedShape);
  if(shape){ V.plate = { value:shape.value.plate, key:shape.key, raw:shape.raw }; V.bedOrigin = { value:shape.value.origin, key:shape.key, raw:shape.raw }; }
  V.maxZ = pick(cfg, ['printable_height', 'max_print_height'], P);
  V.filamentDiameter = pick(cfg, ['filament_diameter'], P) || pick(header, ['filament_diameter'], 'header');
  V.retractLength = pick(cfg, ['retraction_length'], P);
  V.retractSpeed = pick(cfg, ['retraction_speed'], P);
  V.zHop = pick(cfg, ['z_hop'], P);
  V.firstLayerSpeed = pick(cfg, ['initial_layer_speed'], P);
  V.fanMin = pick(cfg, ['fan_min_speed'], P);
  V.fanMax = pick(cfg, ['fan_max_speed'], P);
  V.fanOffFirstLayers = pick(cfg, ['close_fan_the_first_x_layers'], P);
  V.gcodeFlavor = pick(cfg, ['gcode_flavor'], P, s => s);
  V.printerModel = pick(cfg, ['printer_model'], P, s => s) || pick(cfg, ['printer_settings_id'], P, s => s.replace(/^"|"$/g, ''));
  V.printerSettingsId = pick(cfg, ['printer_settings_id'], P, s => s.replace(/^"|"$/g, ''));
  V.filamentType = pick(cfg, ['filament_type'], P, s => firstOf(s));
  return V;
}
