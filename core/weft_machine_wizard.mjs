const sha256 = buf => createHash('sha256').update(buf).digest('hex');
const NUM_RE = /-?\d*\.?\d+(?:[eE][-+]?\d+)?/;
/* first number in a string ("0.45mm" -> 0.45, "220,220" -> 220, "50%" -> 50); null when there is none */
function num(s){ if(s == null) return null; const m = NUM_RE.exec(String(s)); return m ? parseFloat(m[0]) : null; }
/* first element of a per-extruder / per-filament list ("220,220" -> "220") */
function firstOf(s){ return s == null ? null : String(s).split(/[,;]/)[0].trim(); }
function isPercent(s){ return typeof s === 'string' && /%\s*$/.test(s.trim()); }
function round(v, d = 3){ return Math.round(v * 10 ** d) / 10 ** d; }

/* G0/G1 word parser — the gate's regex, applied to the line with its comment removed.
   `N123 G1 …` line numbers are tolerated. Returns null for anything that is not a G0/G1. */
const WORDS = /([XYZEF])(-?\d*\.?\d+)/g;
function parseMove(line){
  const body = line.split(';')[0].trim().replace(/^N\d+\s+/i, '');
  if(!/^G0?[01](?:\s|$)/i.test(body)) return null;
  if(/^G1[0-9]/i.test(body)) return null;             // G10 / G17 … are not moves
  const d = { cmd:body.slice(0, 2).toUpperCase() };
  WORDS.lastIndex = 0; let m; while((m = WORDS.exec(body))) d[m[1]] = parseFloat(m[2]);
  return d;
}
/* the gate's definition: E > 0 and an X or Y on the line */
function isExtrudingXY(d){ return !!d && d.E > 0 && ('X' in d || 'Y' in d); }
function isExtruderReset(line){ return /^\s*G92(?:\s|$)/i.test(line) && /\bE-?\d*\.?\d*/i.test(line.split(';')[0]); }

/* ---------------------------------------------------------------------------------------------------
   input sniffing */
function looksLikeStl(buf, filename){
  if(/\.stl$/i.test(filename || '')) return 'extension .stl';
  if(buf.length >= 84){
    const n = buf.readUInt32LE(80);
    if(84 + 50 * n === buf.length && n > 0) return `binary STL (${n} triangles)`;
  }
  const head = buf.subarray(0, 512).toString('latin1');
  if(/^\s*solid\b/.test(head) && /facet\s+normal|endsolid/i.test(buf.subarray(0, 4096).toString('latin1'))) return 'ascii STL';
  return null;
}
function looksBinary(buf){
  const probe = buf.subarray(0, 8192);
  let zeros = 0, high = 0;
  for(let i = 0; i < probe.length; i++){ const b = probe[i]; if(b === 0) zeros++; else if(b > 0x7e && b < 0xc0) high++; }
  return zeros > 0 || high > probe.length * 0.3;
}
