#!/usr/bin/env node
/* WEFT slicer-export wizard (2026-09-16).

   Turns a file sliced by a desktop slicer into a machine-profile CANDIDATE for machines.json, with
   provenance on every value. It never writes machines.json itself: the entry it produces is a proposal
   for a person to read, and its bead is ALWAYS marked assumed — a slicer's line width is a setting, not
   a bead measured in plastic (USAGE.md, "The one rule").

     parseSlicerExport(bufferOrText, { filename })  -> what the export says, and the start/end blocks
     profileFromExport(parsed, { id, label, outDir }) -> a machines.json entry + a `v2` provenance block
     CLI: node core/weft_machine_wizard.mjs FILE --id NAME --label "..." --out DIR

   Detected inputs
     bambu   Bambu Studio: `.gcode.3mf` container (Metadata/plate_1.gcode) or plain .gcode carrying
             `; HEADER_BLOCK_START … ; CONFIG_BLOCK_START … ; key = value … ; CONFIG_BLOCK_END`,
             signature line `; BambuStudio <version>`.
     orca    OrcaSlicer: same block layout, signature `; generated by OrcaSlicer <version> on <date>`.
     prusa   PrusaSlicer / SuperSlicer: `; generated by PrusaSlicer <version> on <date>`, per-layer
             `;LAYER_CHANGE`, trailing `; prusaslicer_config = begin … ; key = value … = end`.
     cura    Cura: `;FLAVOR:<flavor>`, `;Generated with Cura_SteamEngine <version>`, `;Layer height:`,
             per-layer `;LAYER_COUNT:` / `;LAYER:n`, trailing `;SETTING_3 <json fragments>` whose
             concatenation is JSON holding INI-style profiles ([values] = the settings the user changed).
     unknown Anything else that still contains G/M commands (a Klipper or Marlin file, a bare start
             block). Only what can be read from the moves and the M104/M109/M140/M190 lines is reported.
   Refused: STL (ascii or binary), other binary files, a project .3mf with no sliced G-code member, text
   with no G-code commands at all.

   THE START-BLOCK CUT RULE (documented here because the harvested A2L block defines it)
     exports/a2l_start_block_harvested_2026-09-02.gcode ends at `M981 S1 P20000 ;open spaghetti detector`,
     the last line Bambu Studio writes before its first `; CHANGE_LAYER`. Everything before that marker is
     the machine's, including the nozzle load line (`G130 … E20`) — an extruding move. The gate
     (core/weft_gate.js) agrees: every extrusion before the first `; layer` marker is role `startblock`
     and exempt. So:
       1. If the file has a per-layer marker (`; CHANGE_LAYER` Bambu/Orca, `;LAYER_CHANGE` Prusa,
          `;LAYER_COUNT:`/`;LAYER:` Cura, `; layer N` WEFT), the start block is every line before the
          first marker. Purge / load / intro lines inside it stay, even though they extrude.
       2. Without a marker, the start block ends before the first extruding XY move (G0/G1 with E > 0 and
          an X or Y — the gate's own definition) that is NOT a purge. A purge is a run of extruding moves
          (separated only by other G0/G1 lines) that is closed by a `G92 E…` extruder reset before the
          next run. A file that is only a start block (exports/ender_start.gcode) therefore comes back
          whole, with an empty end block.
     Trailing blank lines are trimmed. Nothing else is touched: header statistics stay (fix_header.py /
     fixHeader() rewrite them from the file's own moves), M73 stays, `; EXECUTABLE_BLOCK_START` stays.

   THE END-BLOCK RULE
     From the line after the last extruding XY move to the end of the file, minus: per-layer / per-object
     comments (`; CHANGE_LAYER`, `; Z_HEIGHT:`, `;LAYER_CHANGE`, `;Z:`, `;HEIGHT:`, `;LAYER:`,
     `;TIME_ELAPSED:`, `; FEATURE:`, `;TYPE:`, `; LINE_WIDTH:`, `;WIDTH:`, `;MESH:`, …), wipe sections
     (`; WIPE_START` … `; WIPE_END`, they carry object coordinates), the slicer's own trailing config
     (`; prusaslicer_config`, `;SETTING_3`, `; objects_info`), print statistics (`; filament used …`,
     `; estimated printing time …`) and `; EXECUTABLE_BLOCK_END` (packBambu3mf owns that line, and the
     harvested A2L end block does not carry it). Leading blank lines are trimmed.

   TEMPLATING
     machines.json start blocks carry `{TEMP}` and `{BED}` (core/weft_core.js substitutes them). The
     template is derived from the harvested block exactly as a2l_start_block_template_2026-09-02.gcode
     was derived from a2l_start_block_harvested_2026-09-02.gcode: an `S<n>` on an M104/M109 line whose n
     equals the export's nozzle temperature (normal or first layer) becomes `S{TEMP}`; the same for
     M140/M190 and the bed. Preheat values (`M104 S140 A`), `G150 T220`, `M620.10 … P220` are left alone.
     Klipper macro arguments (`START_PRINT EXTRUDER_TEMP=220 BED_TEMP=60`) get the same treatment.

   Pure JS, node:zlib through core/weft_build.mjs's own zip reader, deterministic. */
